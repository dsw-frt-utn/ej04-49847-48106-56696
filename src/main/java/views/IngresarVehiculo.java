    private void inicializarComboBox()
    {
        ComboMarca.removeAllItems();
        ComboSucursal.removeAllItems();
        ComboTipo.removeAllItems();
        ComboMarca.addItem("Seleccione Marca");
        ComboSucursal.addItem("Seleccione Sucursal");
        for(Marca marca: Controlador.getMarcas())
        { 
            ComboMarca.addItem(marca.getDescripcion());
        }
        for(Sucursal sucursal: Controlador.getSucursales())
        {
            ComboSucursal.addItem(sucursal.getCodigo());
        }
        
        ComboTipo.addItem("Seleccione Tipo");
        ComboTipo.addItem(VehiculoTipo.COMBUSTIBLE.toString());
        ComboTipo.addItem(VehiculoTipo.ELECTRICO.toString());
        
        
    }

