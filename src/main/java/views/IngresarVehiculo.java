    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String patente = this.patente.getText();
        String marca = this.ComboMarca.getSelectedItem().toString();
        String modelo = this.modelo.getText();
        int anio = Integer.valueOf(this.anio.getText());
        double capCarga = Double.valueOf(this.capCarga.getText());
        String sucursal = this.ComboSucursal.getSelectedItem().toString();
        String tipo = this.ComboTipo.getSelectedItem().toString();
        double kwBase = Double.valueOf(this.kwBase.getText());
        double kmLitros = Double.valueOf(this.kmLitros.getText());
        double kmExtra = Double.valueOf(this.kmExtra.getText());
        
        Controlador.setVehiculos(patente, marca, modelo, anio, capCarga, sucursal, tipo, kwBase, kmLitros, kmExtra);
        this.anio.setText("");
        this.capCarga.setText("");
        this.kmExtra.setText("");
        this.kmLitros.setText("");
        this.kwBase.setText("");
        this.modelo.setText("");
        this.patente.setText("");
        inicializarComboBox();
    }//GEN-LAST:event_jButton1ActionPerformed

    private void ComboTipoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ComboTipoActionPerformed
        Object seleccion = ComboTipo.getSelectedItem();
        if(seleccion == null)
        {
            return;
        }
        
        String tipo = seleccion.toString();
        if(VehiculoTipo.COMBUSTIBLE.toString().equals(tipo))
        {
            
            this.kmLitros.enable(true);
            this.kmExtra.enable(true);
            this.kmLitros.setText("");
            this.kmExtra.setText("");
            this.kwBase.enable(false);
            this.kwBase.setText("0");
        }
        if(VehiculoTipo.ELECTRICO.toString().equals(tipo))
        {
            this.kwBase.enable(true);
            this.kwBase.setText("");
            this.kmLitros.enable(false);
            this.kmExtra.enable(false);
            this.kmLitros.setText("0");
            this.kmExtra.setText("0");
        }
    }//GEN-LAST:event_ComboTipoActionPerformed

